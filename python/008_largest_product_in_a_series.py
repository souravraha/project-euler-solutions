def largest_product(digits: str, length: int) -> int:
    best = 0
    product = 1
    zeros = 0
    for i, ch in enumerate(digits):
        d = int(ch)
        if d == 0:
            zeros += 1
        else:
            product *= d
        if i >= length:  # slide the window left by one
            old = int(digits[i - length])
            if old == 0:
                zeros -= 1
            else:
                product //= old
        if i >= length - 1:
            best = max(best, 0 if zeros else product)
    return best


